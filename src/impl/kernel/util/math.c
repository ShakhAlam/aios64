double cosine(double x) {
    // Normalize x to range [-PI, PI]
    while (x > PI)  x -= TWO_PI;
    while (x < -PI) x += TWO_PI;

    double term = 1.0;
    double sum = 1.0;
    double x2 = x * x;

    for (int i = 1; i <= 10; ++i) {
        term *= -x2 / ((2 * i - 1) * (2 * i));
        sum += term;
    }

    return sum;
}



