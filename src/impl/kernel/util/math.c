double cosine_lut(double x) {
    // Normalize x to [0, TWO_PI)
    while (x < 0)        x += TWO_PI;
    while (x >= TWO_PI)  x -= TWO_PI;

    int degree = (int)(x * (180.0 / PI));  // Convert radians to degrees
    if (degree >= 360) degree = 0;

    return cos_lut[degree];
}


